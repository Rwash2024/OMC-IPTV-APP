// Generates every logo asset from one definition: Android icons, splash screens, web icon, and src/logoData.js.
// Run:  node tools/make-brand-assets.mjs
// The "IPTV" and "OMC" lettering is turned into outlines here, so no font is needed at runtime.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';
import { Resvg } from '@resvg/resvg-js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RED = '#E8301C';
const WHITE = '#FFFFFF';
const DARK = '#0A0C15'; // the app's own background, used for the splash
const res = path.join(root, 'android/app/src/main/res');

// ---- font outlines ----
const fontFile = path.join(root, 'node_modules/@fontsource/outfit/files/outfit-latin-800-normal.woff');
const buf = fs.readFileSync(fontFile);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

// Lays glyphs out one by one (no shaping features needed for plain capitals).
function textPath(text, fontSize, letterSpacing, centerX, baseline) {
  const glyphs = [...text].map((ch) => font.charToGlyph(ch));
  const scale = fontSize / font.unitsPerEm;
  let width = 0;
  glyphs.forEach((g, i) => { width += g.advanceWidth * scale + (i < glyphs.length - 1 ? letterSpacing : 0); });
  const all = new opentype.Path();
  let x = centerX - width / 2;
  for (const g of glyphs) {
    all.commands.push(...g.getPath(x, baseline, fontSize).commands);
    x += g.advanceWidth * scale + letterSpacing;
  }
  return { d: all.toPathData(2), width, box: all.getBoundingBox() };
}

// ---- logo geometry (120x120 tile) ----
const ARCH = 'M45.6 74.2 A26.5 26.5 0 1 1 74.4 74.2';
const iptv = textPath('IPTV', 17, 3.5, 60, 103);

const symbol = (fill) =>
  `<path d="${ARCH}" fill="none" stroke="${fill}" stroke-width="11.5"/><rect x="54.6" y="41" width="10.8" height="34" rx="5.4" fill="${fill}"/>`;
const content = (fill) => `${symbol(fill)}<path d="${iptv.d}" fill="${fill}"/>`;

// Content bounds in tile units: x 27.75..92.25, y 19.75..103 (IPTV baseline). Centre y ~ 61.4.
const CX = 60, CY = 61.4, CH = 83.3;
const fitted = (canvas, ratio, fill) => {
  const s = (ratio * canvas) / CH;
  return `<g transform="translate(${canvas / 2} ${canvas / 2}) scale(${s}) translate(${-CX} ${-CY})">${content(fill)}</g>`;
};

const tileSvg = (size) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 120 120"><rect width="120" height="120" rx="28" fill="${RED}"/>${content(WHITE)}</svg>`;
const roundSvg = (size) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><circle cx="${size / 2}" cy="${size / 2}" r="${size / 2}" fill="${RED}"/>${fitted(size, 0.58, WHITE)}</svg>`;
const foregroundSvg = (size) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">${fitted(size, 0.5, WHITE)}</svg>`;
const splashSvg = (w, h) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}"><rect width="${w}" height="${h}" fill="${DARK}"/></svg>`; // plain dark: the logo is drawn by the in-app opening animation

const png = (svg, width) => new Resvg(svg, { fitTo: { mode: 'width', value: width } }).render().asPng();
const write = (file, data) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, data); };

// ---- Android launcher icons ----
const legacy = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [d, px] of Object.entries(legacy)) {
  write(path.join(res, `mipmap-${d}/ic_launcher.png`), png(tileSvg(px), px));
  write(path.join(res, `mipmap-${d}/ic_launcher_round.png`), png(roundSvg(px), px));
  const fg = Math.round((px / 48) * 108);
  write(path.join(res, `mipmap-${d}/ic_launcher_foreground.png`), png(foregroundSvg(fg), fg));
}
write(path.join(res, 'values/ic_launcher_background.xml'),
  `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${RED}</color>\n</resources>\n`);

// ---- Splash screens (same sizes as the ones already in the project) ----
const pngSize = (file) => { const b = fs.readFileSync(file); return [b.readUInt32BE(16), b.readUInt32BE(20)]; };
for (const dir of fs.readdirSync(res).filter((n) => /^drawable(-(land|port)-\w+)?$/.test(n))) {
  const f = path.join(res, dir, 'splash.png');
  if (!fs.existsSync(f)) continue;
  const [w, h] = pngSize(f);
  write(f, png(splashSvg(w, h), w));
}

// ---- Web assets ----
write(path.join(root, 'public/icon.svg'), tileSvg(512).replace('width="512" height="512"', 'width="512" height="512"'));
write(path.join(root, 'public/icon-512.png'), png(tileSvg(512), 512));

const omc = textPath('OMC', 40, 6, 0, 40);
const b = omc.box;
write(path.join(root, 'src/logoData.js'),
  `// Generated by tools/make-brand-assets.mjs. Do not edit by hand.\n` +
  `export const RED = '${RED}';\n` +
  `export const ARCH = '${ARCH}';\n` +
  `export const IPTV_PATH = '${iptv.d}';\n` +
  `export const OMC_PATH = '${omc.d}';\n` +
  `export const OMC_BOX = [${[b.x1, b.y1, b.x2 - b.x1, b.y2 - b.y1].map((n) => +n.toFixed(2)).join(', ')}];\n`);

console.log('Brand assets written.');
